def country_name(code: str | None) -> str | None:
    if not code:
        return None
    key = code.strip().lower()
    return COUNTRY_NAMES.get(key, key.upper())


def language_name(code: str | None) -> str | None:
    if not code:
        return None
    key = code.strip().lower()
    return LANGUAGE_NAMES.get(key, key.upper())
